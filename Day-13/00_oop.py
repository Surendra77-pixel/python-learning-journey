#why we use the oop?

#1. code reusability - we can create a class and then create multiple objects from that class with different attributes and behaviors.this makes code more organized and easier to maintain.

#2. encapsulation - we can hide the internal details of a class and only expose the necessary information.this makes code more secure and easier to maintain.

#3. inheritance - we can create a new class that inherits the properties and behaviors of an existing class.this allows us to reuse code and create new functionality without having to rewrite existing code.

#4. polymorphism - we can use the same method name to perform different tasks.this allows us to write code that is more flexible and easier to maintain.

#what is the difference between oop and procedural programming?

#procedural programming is a programming paradigm that focuses on writing procedures or routines that operate on data. It is based on the concept of procedures or functions that take input, process it, and produce output. In procedural programming, the code is organized around procedures or functions, and data is often stored in global variables.

#On the other hand, object-oriented programming (OOP) is a programming paradigm that focuses on creating objects that contain both data and behavior. In OOP, the code is organized around classes and objects, and data is often stored in instance variables. OOP allows for better organization, reusability, and maintainability of code compared to procedural programming.

#In summary, procedural programming focuses on writing procedures or functions that operate on data, while object-oriented programming focuses on creating objects that contain both data and behavior. OOP provides better organization, reusability, and maintainability of code compared to procedural programming.

#In procedural programming, the code is organized around procedures or functions, and data is often stored in global variables. In contrast, in object-oriented programming (OOP), the code is organized around classes and objects, and data is often stored in instance variables. OOP allows for better organization, reusability, and maintainability of code compared to procedural programming.
